let currentLang = localStorage.getItem('nexa_lang') || 'en';

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('nexa_lang', lang);

  // Update html lang and dir for RTL
  const htmlEl = document.documentElement;
  const bodyEl = document.body;
  const rtlLangs = ['ar', 'he'];
  htmlEl.setAttribute('lang', lang);
  htmlEl.setAttribute('dir', rtlLangs.includes(lang) ? 'rtl' : 'ltr');
  bodyEl.setAttribute('dir', rtlLangs.includes(lang) ? 'rtl' : 'ltr');

  // Update all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update select dropdowns to show selected
  document.querySelectorAll('#langSwitch, #footerLangSwitch').forEach(sel => {
    if (sel) sel.value = lang;
  });
}

function initI18n() {
  const switches = document.querySelectorAll('#langSwitch, #footerLangSwitch');
  switches.forEach(sel => {
    sel.value = currentLang;
    sel.addEventListener('change', (e) => setLanguage(e.target.value));
  });
  setLanguage(currentLang);
}

// Expose globally for inline onclick if needed
window.setLanguage = setLanguage;
window.initI18n = initI18n;

function copyAddress(id) {
  const el = document.getElementById(id);
  if (!el) return;
  const text = el.textContent.trim();
  navigator.clipboard.writeText(text).then(() => {
    const original = el.textContent; // not used, button text changes instead
    const btn = el.parentElement.querySelector('button');
    if (btn) {
      const oldText = btn.textContent;
      btn.textContent = 'Copied!';
      setTimeout(() => btn.textContent = oldText, 1500);
    }
  });
}

